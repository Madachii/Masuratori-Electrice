"""PXR register addresses, in PDU (zero-based) form.

The manual writes holding registers as 4xxxx. Subtract 400001 to get the
address pymodbus puts on the wire: 404497 -> 4496.
"""

DEVICE_NAME_ADDRESS = 4496  # 404497, "EATON PXR20" / "EATON PXR25"
DEVICE_NAME_COUNT = 8  # 16 ASCII characters

# Device information, section 9.3.13 in the PXR manual.
SERIAL_NUMBER_ADDRESS = 4544  # 404545, 0x11C0
SERIAL_NUMBER_COUNT = 16  # 32 ASCII characters, "if supported"

# Currents, IEEE float, two registers each.
CURRENT_L1_ADDRESS = 4610  # 404611
CURRENT_L2_ADDRESS = 4612  # 404613
CURRENT_L3_ADDRESS = 4614  # 404615
CURRENT_GROUND_ADDRESS = 4616  # 404617
CURRENT_NEUTRAL_ADDRESS = 4618  # 404619
CURRENT_COUNT = 2

# Voltages, IEEE float, two registers each.
VOLTAGE_L1_L2_ADDRESS = 4622  # 404623
VOLTAGE_L2_L3_ADDRESS = 4624  # 404625
VOLTAGE_L3_L1_ADDRESS = 4626  # 404627
VOLTAGE_L1_N_ADDRESS = 4630  # 404631
VOLTAGE_L2_N_ADDRESS = 4632  # 404633
VOLTAGE_L3_N_ADDRESS = 4634  # 404635
VOLTAGE_COUNT = 2

# Power, IEEE float, two registers each.
ACTIVE_POWER_ADDRESS = 4650  # 404651
REACTIVE_POWER_ADDRESS = 4652  # 404653
APPARENT_POWER_ADDRESS = 4654  # 404655
POWER_FACTOR_ADDRESS = 4658  # 404659
FREQUENCY_ADDRESS = 4660  # 404661
POWER_COUNT = 2

# Peak demand, IEEE float, two registers each.
PEAK_ACTIVE_POWER_ADDRESS = 4696  # 404697
PEAK_REACTIVE_POWER_ADDRESS = 4796  # 404797
PEAK_APPARENT_POWER_ADDRESS = 4798  # 404799

# Power demand, IEEE float, two registers each.
